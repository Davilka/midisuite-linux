#!/usr/bin/env bash
#
# Build all release assets:
#   dist/midisuite_linux-<version>-py3-none-any.whl
#   dist/midisuite_linux-<version>.tar.gz        (sdist, optional)
#   dist/midisuite-gui-linux-x86_64-<version>.tar.gz
#   dist/SHA256SUMS
#
# Usage: scripts/build-bundle.sh [version]
#
# Set MIDISUITE_SKIP_SDIST=1 to skip the source distribution.  The release
# workflow uses this because GitHub provides the source archive itself.
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

VERSION="${1:-$(python -c 'import tomllib;print(tomllib.load(open("pyproject.toml","rb"))["project"]["version"])')}"

# Bake the update repository into the build so the released bundle can check
# GitHub Releases without any configuration.
BUILD_INFO="src/midisuite/_build_info.py"
rm -f "$BUILD_INFO"
cleanup() { rm -f "$BUILD_INFO"; }
trap cleanup EXIT
if [ -n "${MIDISUITE_UPDATE_REPO:-}" ]; then
    printf '# Generated by scripts/build-bundle.sh\nREPO = "%s"\n' \
        "$MIDISUITE_UPDATE_REPO" > "$BUILD_INFO"
    echo "==> update repository: $MIDISUITE_UPDATE_REPO"
fi
BUNDLE="midisuite-gui-linux-x86_64"
ARCHIVE="$BUNDLE-$VERSION.tar.gz"

echo "==> building version $VERSION"

python -m pip install --quiet --upgrade build pyinstaller
rm -rf dist build/pyinstaller
mkdir -p dist

if [ "${MIDISUITE_SKIP_SDIST:-0}" = "1" ]; then
    echo "==> wheel (sdist skipped)"
    python -m build --wheel --outdir dist
else
    echo "==> wheel and sdist"
    python -m build --outdir dist
fi

echo "==> PyInstaller bundle"
pyinstaller \
    --noconfirm \
    --clean \
    --windowed \
    --name midisuite-gui \
    --collect-submodules dbus_fast \
    --distpath build/pyinstaller/dist \
    --workpath build/pyinstaller/work \
    --specpath build/pyinstaller \
    packaging/launcher.py

mkdir -p "dist/$BUNDLE"
cp -a "build/pyinstaller/dist/midisuite-gui/." "dist/$BUNDLE/"
cp README.md LICENSE THIRD_PARTY_NOTICES.md "dist/$BUNDLE/"
mkdir -p "dist/$BUNDLE/docs"
cp docs/protocol.md docs/CLEAN_ROOM.md docs/BUILD.md docs/INSTALL.md "dist/$BUNDLE/docs/"
cp docs/screenshot.png docs/led-test.png "dist/$BUNDLE/docs/"
mkdir -p "dist/$BUNDLE/contrib"
cp contrib/midisuite.desktop contrib/midisuite.svg "dist/$BUNDLE/contrib/"
cat > "dist/$BUNDLE/README-bundle.txt" <<'TXT'
This is a self-contained build of the SMC-Mixer editor.

Run:
    ./midisuite-gui

Full installation instructions:
    docs/INSTALL.md

Optional desktop integration:
    mkdir -p ~/.local/opt ~/.local/share/applications ~/.local/share/icons/hicolor/scalable/apps
    cp -r . ~/.local/opt/midisuite
    cp contrib/midisuite.svg ~/.local/share/icons/hicolor/scalable/apps/midisuite.svg
    sed "s|Exec=midisuite-gui|Exec=$HOME/.local/opt/midisuite/midisuite-gui|" \
        contrib/midisuite.desktop > ~/.local/share/applications/midisuite.desktop
TXT

tar -C dist -czf "dist/$ARCHIVE" "$BUNDLE"

echo "==> checksums"
(
    cd dist
    sha256sum ./*.whl ./*.tar.gz > SHA256SUMS
    cat SHA256SUMS
)

echo "==> done"
